import { test, expect } from '@playwright/test';
import { randomBytes } from 'node:crypto';
import { config } from '../../public/content.js';

test('canjes disponibles después de recargar, con nombre seguro y extra actualizado', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const issued = await page.request.post('/api/participations', { data: { eventId: config.eventId, key: randomBytes(32).toString('hex'), name: 'Ana <img src=x onerror=alert(1)>', career: 'sistemas', answers: [0, 0, 0, 0, 0, 0] } });
  expect(issued.status()).toBe(200);
  const ticket = await issued.json();
  await page.goto('/admin');
  await page.getByLabel('Contraseña del equipo').fill('only-for-automated-tests');
  await page.getByRole('button', { name: 'Ingresar al panel' }).click();
  await page.getByLabel('Código del participante').fill(ticket.code);
  await page.getByRole('button', { name: 'Consultar', exact: true }).click();
  await page.getByRole('button', { name: 'Confirmar canje inicial' }).click();
  await expect(page.locator('#coupon .done')).toHaveCount(1);
  await page.reload();
  await page.getByRole('button', { name: 'Ver ya canjeados', exact: true }).click();
  const row = page.locator('.redeemed-list li').filter({ hasText: ticket.code });
  await expect(row).toContainText(ticket.name);
  await expect(row).toContainText('Ingeniería en Sistemas de Información');
  await expect(row).toContainText('Sin canjear');
  await expect(row.locator('img')).toHaveCount(0);
  await page.getByLabel('Código del participante').fill(ticket.code);
  await page.getByRole('button', { name: 'Consultar', exact: true }).click();
  await page.locator('#confirmed').check();
  await page.getByRole('button', { name: 'Confirmar canje extra' }).click();
  await expect(row).not.toContainText('Sin canjear');
  await page.reload();
  await page.getByRole('button', { name: 'Ver ya canjeados', exact: true }).click();
  await expect(row).toBeVisible();
  await expect(row).not.toContainText('Sin canjear');
  await page.route('**/api/admin/redeemed*', route => route.abort());
  await page.getByRole('button', { name: 'Actualizar listado' }).click();
  await expect(page.getByRole('button', { name: 'Reintentar listado' })).toBeVisible();
  await page.unroute('**/api/admin/redeemed*');
  await page.getByRole('button', { name: 'Reintentar listado' }).click();
  await expect(row).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
